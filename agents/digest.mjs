// Digest agent: writes ~/Documents/job-hunt-digest-YYYY-MM-DD.md (same convention as the
// existing digests) and queues it in the outbox. Sends immediately when
// config.email.auto_send_digest is true, or when { send: true } is passed.
import fs from 'fs'
import os from 'os'
import path from 'path'
import { addJournal, startRun, finishRun, uid, nowIso, today, lastRun } from './lib/store.mjs'
import { sendMail, mdToHtml, emailConfigured } from './lib/email.mjs'

const money = n => (n ? `$${Math.round(n / 1000)}k` : '—')
const comp = d => (d.salary_min || d.salary_max) ? `${money(d.salary_min)}–${money(d.salary_max)}` : '—'
const perks = d => (d.perks || []).length ? d.perks.join(', ') : '—'
const loc = d => (d.location_policy === 'remote' ? 'Remote' : d.location) + (d.alt_locations?.length ? ` +${d.alt_locations.length}` : '')

export function buildDigest(data) {
  const t = today()
  const cfg = data.config
  const since = new Date(Date.now() - 36 * 3600 * 1000).toISOString()
  const newRoles = data.discovered.filter(d => d.status === 'new' && d.first_seen >= since).sort((a, b) => b.score - a.score)
  const hot = data.discovered.filter(d => d.status === 'new' && ['A', 'B'].includes(d.grade)).sort((a, b) => b.score - a.score).slice(0, 10)
  const signals = data.email_signals.filter(s => s.ts >= since)
  const imps = data.improvements.filter(i => i.severity !== 'low')
  const active = data.jobs.filter(j => ['Applied', 'Phone Screen', 'Technical Screen', 'Onsite', 'Offer'].includes(j.status))
  const fetchRun = lastRun(data, 'fetch'), scanRun = lastRun(data, 'scan')

  const L = []
  L.push(`# 🎯 Vamsi's Job Hunt Digest — ${t}`, '')
  L.push(`Policy: **Dallas onsite or remote anywhere** · Target: Staff/Principal · Floor: ${money(cfg.min_salary)} · Prefer: 401k match, equity, growth-stage tech`, '')
  L.push(`## 🆕 New since yesterday (${newRoles.length})`, '')
  if (newRoles.length) {
    L.push('| Grade | Company | Role | Location | Comp | Perks | Apply |', '|---|---|---|---|---|---|---|')
    for (const d of newRoles.slice(0, 15)) L.push(`| ${d.grade}${d.score} | ${d.company} | ${d.role_title} | ${loc(d)} | ${comp(d)} | ${perks(d)} | [Link](${d.url}) |`)
  } else L.push('No new matching roles from the watched boards in the last 36 hours.')
  L.push('', `## ✅ Best unreviewed roles in the feed (${hot.length})`, '')
  for (const d of hot) L.push(`- **${d.grade}${d.score}** ${d.company} — ${d.role_title} · ${loc(d)} · ${comp(d)} · ${d.score_reasons.slice(0, 3).join(', ')} · [apply](${d.url})`)
  if (!hot.length) L.push('Feed is clear.')
  L.push('', `## 📬 Email signals (${signals.length})`, '')
  for (const s of signals) L.push(`- **${s.classification}**${s.company ? ' · ' + s.company : ''} — ${s.subject}${s.applied ? ' ✓ applied' : ' (pending)'}`)
  if (!signals.length) L.push('No application-related email in the window.')
  L.push('', `## 🔧 Improvements (${imps.length})`, '')
  for (const i of imps.slice(0, 12)) L.push(`- [${i.severity}] **${i.title}** — ${i.body}`)
  if (!imps.length) L.push('Nothing flagged.')
  L.push('', `## 📊 Pipeline`, '')
  L.push(`- Active: ${active.length} · Total tracked: ${data.jobs.length} · Feed new: ${data.discovered.filter(d => d.status === 'new').length}`)
  const byStatus = {}; for (const j of data.jobs) byStatus[j.status] = (byStatus[j.status] || 0) + 1
  L.push(`- By status: ${Object.entries(byStatus).map(([k, v]) => `${k} ${v}`).join(' · ')}`)
  L.push(`- Last fetch: ${fetchRun ? `${fetchRun.status} ${fetchRun.started_at.slice(0, 16).replace('T', ' ')} — ${fetchRun.summary}` : 'never'}`)
  L.push(`- Last scan: ${scanRun ? `${scanRun.status} ${scanRun.started_at.slice(0, 16).replace('T', ' ')} — ${scanRun.summary}` : 'never'}`)
  L.push('', '---', `_Generated by job-tracker agents · ${nowIso()}_`)
  return L.join('\n')
}

export async function runDigest(data, { trigger = 'manual', send = null, outDir = null } = {}) {
  const run = startRun(data, 'digest', trigger)
  const md = buildDigest(data)
  const dir = outDir || process.env.DIGEST_DIR || path.join(os.homedir(), 'Documents')
  const file = path.join(dir, `job-hunt-digest-${today()}.md`)
  try { fs.writeFileSync(file, md) } catch { /* non-fatal: outbox still holds the digest */ }
  const to = data.config.email?.to
  const shouldSend = send ?? !!data.config.email?.auto_send_digest
  const item = { id: uid('o_'), ts: nowIso(), to, subject: `Job Hunt Digest — ${today()}`, body: md, format: 'markdown', job_id: null, kind: 'digest', status: 'draft', sent_at: null, error: null }
  data.outbox.push(item)
  let sent = false, error = null
  if (shouldSend && to) {
    try {
      if (!emailConfigured()) throw new Error('email not configured')
      await sendMail({ to, subject: item.subject, body: mdToHtml(md), html: true, replyTo: data.config.email?.reply_to })
      item.status = 'sent'; item.sent_at = nowIso(); sent = true
    } catch (e) { item.status = 'failed'; item.error = e.message; error = e.message }
  }
  const summary = `Digest written to ${file}${sent ? ` and emailed to ${to}` : shouldSend ? ` (send failed: ${error})` : ' (draft in outbox)'}`
  finishRun(data, run.id, { status: error ? 'error' : 'ok', summary, stats: { file, sent, outbox_id: item.id }, error })
  addJournal(data, { type: 'agent', title: `Digest ${today()}`, body: summary, source: 'agent:digest', meta: { run_id: run.id, outbox_id: item.id } })
  return { run, file, md, sent, outbox: item }
}
